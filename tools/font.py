#!/usr/bin/env python3
# Writes src/font/glyphs.nabi: outlines and advances of the built-in
# font. Geist (regular, wght 400) first, Pretendard for the codepoints
# Geist lacks (Greek, some math). Both are OFL-1.1; see assets/fonts.
#
#   python3 tools/font.py <Geist-Variable.woff2> <pretendard dir> > src/font/glyphs.nabi
#
# Needs fontTools and brotli.

import glob
import sys

from fontTools.pens.basePen import decomposeQuadraticSegment
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

RANGES = [
    (0x20, 0x7E),
    (0xA0, 0xFF),
    (0x391, 0x3A9),
    (0x3B1, 0x3C9),
    (0x3D1, 0x3D1),
    (0x3D5, 0x3D5),
    (0x3F5, 0x3F5),
    (0x2013, 0x2014),
    (0x2018, 0x201D),
    (0x2022, 0x2022),
    (0x2026, 0x2026),
    (0x2030, 0x2030),
    (0x2032, 0x2033),
    (0x2070, 0x209C),
    (0x2103, 0x2103),
    (0x2190, 0x2193),
    (0x2202, 0x2202),
    (0x2207, 0x2208),
    (0x220F, 0x220F),
    (0x2211, 0x2212),
    (0x221A, 0x221A),
    (0x221D, 0x221E),
    (0x222B, 0x222B),
    (0x223C, 0x223C),
    (0x2248, 0x2248),
    (0x2260, 0x2260),
    (0x2264, 0x2265),
    (0x22C5, 0x22C5),
]


def load(path):
    f = TTFont(path)
    if "fvar" in f:
        f = instancer.instantiateVariableFont(f, {"wght": 400})
    return f


def outline(font, name, scale):
    gs = font.getGlyphSet()
    pen = DecomposingRecordingPen(gs)
    gs[name].draw(pen)
    ops = []
    cur = None
    start = None

    def pt(p):
        return (round(p[0] * scale), round(p[1] * scale))

    for op, args in pen.value:
        if op == "moveTo":
            cur = start = args[0]
            ops.append((0,) + pt(cur))
        elif op == "lineTo":
            cur = args[0]
            ops.append((1,) + pt(cur))
        elif op == "qCurveTo":
            pts = list(args)
            if pts[-1] is None:
                # a contour of off-curve points only
                pts = pts[:-1]
                mid = ((pts[-1][0] + pts[0][0]) / 2, (pts[-1][1] + pts[0][1]) / 2)
                ops.append((0,) + pt(mid))
                pts = pts + [mid]
            for c, e in decomposeQuadraticSegment(pts):
                ops.append((2,) + pt(c) + pt(e))
                cur = e
        elif op == "curveTo":
            raise SystemExit("cubic outlines are not expected in a TrueType font")
        elif op in ("closePath", "endPath"):
            ops.append((3,))
            cur = start
    return ops


def main():
    geist = load(sys.argv[1])
    extra = [load(p) for p in sorted(glob.glob(sys.argv[2] + "/*.woff2"))]
    upm = geist["head"].unitsPerEm
    gmap = geist.getBestCmap()
    rows = []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            src = None
            if cp in gmap:
                src = (geist, gmap[cp])
            else:
                for f in extra:
                    m = f.getBestCmap()
                    if cp in m:
                        src = (f, m[cp])
                        break
            if src is None:
                continue
            f, name = src
            scale = upm / f["head"].unitsPerEm
            adv = round(f["hmtx"][name][0] * scale)
            rows.append((cp, adv, outline(f, name, scale)))
    hhea = geist["hhea"]
    os2 = geist["OS/2"]
    codes, advs, starts, data = [], [], [0], []
    for cp, adv, ops in rows:
        codes.append(cp)
        advs.append(adv)
        for o in ops:
            data.extend(o)
        starts.append(len(data))
    out = []
    out.append("// Generated by tools/font.py from Geist and Pretendard (both SIL OFL 1.1,")
    out.append("// assets/fonts). Do not edit.")
    out.append("")
    out.append(f"pub(pkg) const UNITS: f64 = {float(upm)};")
    out.append(f"pub(pkg) const ASCENT: f64 = {float(hhea.ascent)};")
    out.append(f"pub(pkg) const DESCENT: f64 = {float(hhea.descent)};")
    out.append(f"pub(pkg) const CAP: f64 = {float(os2.sCapHeight)};")
    out.append(f"pub(pkg) const XHEIGHT: f64 = {float(os2.sxHeight)};")
    out.append(f"pub(pkg) const COUNT: usize = {len(codes)};")
    out.append("")
    out.append("// Codepoints, rising.")
    out.append(table("CODES", "u32", codes))
    out.append("")
    out.append("// Advance widths in font units.")
    out.append(table("ADVANCES", "u16", advs))
    out.append("")
    out.append("// Glyph i is OUTLINES[STARTS[i]..STARTS[i + 1]]: 0 x y = move,")
    out.append("// 1 x y = line, 2 cx cy x y = quadratic, 3 = close; y up.")
    out.append(table("STARTS", "u32", starts))
    out.append("")
    out.append(table("OUTLINES", "i16", data))
    sys.stdout.write("\n".join(out) + "\n")


def table(name, ty, xs):
    lines = [f"pub(pkg) const {name}: [{ty}; {len(xs)}] = ["]
    for i in range(0, len(xs), 16):
        lines.append("    " + ", ".join(str(x) for x in xs[i:i + 16]) + ",")
    lines.append("];")
    return "\n".join(lines)


main()
