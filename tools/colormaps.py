#!/usr/bin/env python3
# Writes src/colormap/tables.nabi from the published colormap data as
# matplotlib ships it: viridis, magma, inferno, plasma (van der Walt and
# Smith, CC0), cividis (Nunez, Anderton and Renslow 2018) as 256-entry
# tables, and Moreland's coolwarm (2009) as its 33 control points.
#
#   python3 tools/colormaps.py > src/colormap/tables.nabi
#
# Needs matplotlib (only to read its data modules).

import sys

import matplotlib._cm as cm
import matplotlib._cm_listed as listed


def table(name, xs):
    lines = [f"pub(pkg) const {name}: [f64; {len(xs)}] = ["]
    for i in range(0, len(xs), 6):
        lines.append("    " + ", ".join(repr(float(x)) for x in xs[i:i + 6]) + ",")
    lines.append("];")
    return "\n".join(lines)


def main():
    out = ["// Generated by tools/colormaps.py from matplotlib's colormap data. Do", "// not edit.", ""]
    for name in ["viridis", "magma", "inferno", "plasma", "cividis"]:
        data = getattr(listed, f"_{name}_data")
        flat = [c for rgb in data for c in rgb]
        out.append(f"// {name}: 256 RGB triples in [0, 1].")
        out.append(table(name.upper(), flat))
        out.append("")
    d = cm._coolwarm_data
    flat = []
    for i in range(len(d["red"])):
        flat.extend([d["red"][i][0], d["red"][i][1], d["green"][i][1], d["blue"][i][1]])
    out.append("// coolwarm: 33 control points as (position, r, g, b).")
    out.append(table("COOLWARM", flat))
    sys.stdout.write("\n".join(out) + "\n")


main()
